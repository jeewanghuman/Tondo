#!/usr/bin/env python3
"""Turn the gzipped single-file web app (and the home-screen icons) into a C
header (flash-resident)."""
import os
import sys

src, dst = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))


def array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    body = '\n'.join(lines)
    return (f'constexpr size_t {name}Len = {len(data)};\n'
            f'constexpr uint8_t {name}[] = {{\n{body}\n}};\n')


app = open(src, 'rb').read()
parts = [array('kWebAppGz', app)]
# The PNGs in public/ are committed (tools/webapp/gen_icons.py draws them).
icons = (('kIcon192', 'icon-192.png'), ('kIcon512', 'icon-512.png'),
         ('kAppleTouchIcon', 'apple-touch-icon.png'))
total = len(app)
for sym, fname in icons:
    data = open(os.path.join(here, 'public', fname), 'rb').read()
    parts.append(array(sym, data))
    total += len(data)

open(dst, 'w').write("""#pragma once

#include <cstddef>
#include <cstdint>

// GENERATED by tools/webapp/build.sh — do not edit. kWebAppGz is the gzipped
// single-file React app served at '/', the kIcon* arrays the home-screen icons
// (see platform_esp32/web_ui.cpp). Rebuilt by `make webapp` (needs node).

namespace platform {

""" + '\n'.join(parts) + """
}  // namespace platform
""")
print(f'{dst}: {total} bytes')
